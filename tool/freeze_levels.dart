// ignore_for_file: avoid_print
// Curates and freezes campaign levels 1–50 into
// lib/game/levels/handcrafted_levels.dart.
//
// Levels 1–3 are hand-designed teaching boards. Levels 4–50 are drawn from
// the generator, each checked by the solver, with a curated difficulty
// ramp (gentle start inside every band of ten, one "spike" level per band).
//
//   dart run tool/freeze_levels.dart
import 'dart:io';

import 'package:sort_sphere/game/generator/ball_sort_level_generator.dart';
import 'package:sort_sphere/game/generator/difficulty_analyzer.dart';
import 'package:sort_sphere/game/levels/level_catalog.dart';
import 'package:sort_sphere/game/solver/ball_sort_solver.dart';
import 'package:sort_sphere/models/difficulty.dart';
import 'package:sort_sphere/models/level_data.dart';

const handDesigned = <List<List<int>>>[
  // 1 — two colors, one swap teaches "move onto the same color / empty".
  [[0, 0, 1, 1], [1, 1, 0, 0], []],
  // 2 — alternating colors, two helpers.
  [[0, 1, 0, 1], [1, 0, 1, 0], [], []],
  // 3 — first three-color board.
  [[0, 1, 2, 0], [1, 2, 0, 1], [2, 0, 1, 2], [], []],
];

void main() {
  final solver = BallSortSolver(maxNodes: 200000, weight: 1);
  final levels = <LevelData>[];
  for (var i = 0; i < handDesigned.length; i++) {
    final b = handDesigned[i];
    final path = solver.findSolution(b, 4).path!;
    final m = DifficultyAnalyzer.analyze(b, 4, path);
    levels.add(LevelData(number: i + 1, tubes: b, capacity: 4, difficulty: Difficulty.tutorial, par: path.length, score: m.score));
  }
  final gen = BallSortLevelGenerator(solver: solver, candidates: 8);
  for (var n = handDesigned.length + 1; n <= LevelCatalog.handcraftedCount; n++) {
    final d = LevelCatalog.difficultyFor(n);
    final inBand = (n - 1) % 10; // 0..9 position inside band
    // Ramp: early levels in a band aim below the tier target, level 9 spikes.
    final offset = inBand == 8 ? 4 : inBand - 5;
    final target = d.target + offset;
    var colors = d.colors;
    if (n <= 5) colors = 3;
    final cfg = GeneratorConfig(difficulty: d, seed: LevelCatalog.seedFor(n), colorCount: colors, levelNumber: n);
    LevelData? best;
    for (var s = 0; s < 6; s++) {
      final l = gen.generate(GeneratorConfig(
        difficulty: cfg.difficulty,
        seed: cfg.seed + s,
        colorCount: cfg.colorCount,
        levelNumber: n,
      ));
      if (best == null || (l.score - target).abs() < (best.score - target).abs()) best = l;
    }
    final check = solver.findSolution(best!.tubes, best.capacity);
    if (!check.solved) throw StateError('Level $n unsolvable');
    levels.add(best);
    print('L$n ${d.name} colors=${best.colorCount} tubes=${best.tubeCount} par=${best.par} score=${best.score}');
  }

  final sb = StringBuffer()
    ..writeln('// GENERATED by tool/freeze_levels.dart — curated campaign levels 1–50.')
    ..writeln('// Every level is verified solvable by BallSortSolver (see test/levels_test.dart).')
    ..writeln("import '../../models/difficulty.dart';")
    ..writeln("import '../../models/level_data.dart';")
    ..writeln()
    ..writeln('const List<LevelData> handcraftedLevels = [');
  for (final l in levels) {
    sb.writeln('  LevelData(number: ${l.number}, capacity: ${l.capacity}, difficulty: Difficulty.${l.difficulty.name}, '
        'par: ${l.par}, seed: ${l.seed}, score: ${l.score}, tubes: ${l.tubes}),');
  }
  sb.writeln('];');
  File('lib/game/levels/handcrafted_levels.dart').writeAsStringSync(sb.toString());
  print('Wrote ${levels.length} levels.');
}
